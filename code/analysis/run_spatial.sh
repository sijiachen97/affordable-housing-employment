#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")/../.."
ROOT="$PWD/output/research_extensions/23_spatial_spillover"
PREP="code/data_process/spatial"
FINAL="code/analysis/spatial"
mkdir -p "$ROOT/stage_a" "$ROOT/stage_b" "$ROOT/stage_c" "$ROOT/stage_j/matching"
# Original frozen county-pair checks required by spatial common.R.
Rscript "$PREP/legacy_county_pairs.R"
Rscript "$PREP/run.R" "$ROOT/stage_a"
Rscript "$PREP/project_coordinates.R" "$ROOT/stage_a"
Rscript "$PREP/match_regions.R" "$ROOT/stage_a" "$ROOT/stage_b"
Rscript "$PREP/match_center_surroundings.R" "$ROOT/stage_a" "$ROOT/stage_b" "$ROOT/stage_c"
Rscript "$PREP/rematch_state_isolated.R" "$ROOT/stage_a" "$ROOT/stage_b" "$ROOT/stage_j/matching"
N="$ROOT/stage_n/work"
mkdir -p "$N/stage_a" "$N/stage_b" "$N/stage_j/matching"
Rscript "$PREP/prepare_7km_cache.R" "$ROOT" "$N"
Rscript "$PREP/prepare_7km_eligibility.R" "$N/stage_a" "$N/stage_b"
O="$ROOT/stage_o"
mkdir -p "$O/work/stage_a" "$O/work/stage_b" "$O/work/stage_h/matching" "$O/work/stage_j/matching" "$O/estimates"
Rscript "$FINAL/prepare.R" "$ROOT" "$O/work"
Rscript "$FINAL/match_guarded_regions.R" "$O/work/stage_a" "$O/work/stage_b" "$O/work/stage_h/matching"
Rscript "$FINAL/estimate_guarded_regions.R" "$O/work" "$O/estimates"
Rscript "$FINAL/validate.R" "$O/work" "$O/estimates"
Rscript "$FINAL/plot_standalone.R" "$O"
