source(file.path(Sys.getenv('LIHTC_REFRESH_OUTPUT'),'engine.R'))
side<-commandArgs(TRUE)[1];stopifnot(side%in%c('rac','wac'))
z<-read_parquet(path(paste0('data_raw/LODES/OD_related/lodes7_tract_agg_2010_2019/lodes_',side,'_outcomes_tract2010_2010_2019.parquet')))%>%mutate(tract_id=as.numeric(.data[[if(side=='rac')'h_tract' else 'w_tract']]),year=as.integer(year))
sectors<-sprintf('CNS%02d',1:20)
stopifnot(!anyDuplicated(z[c('tract_id','year')]),all(rowSums(z[,sectors])==z$C000))
p<-left_join(p,z%>%select(tract_id,year,total_jobs=C000,all_of(sectors)),by=c('tract_id','year'))
stopifnot(max(abs(p$total_jobs-p[[paste0(side,'_total')]]),na.rm=TRUE)==0)
for(y in c('total_jobs',sectors))p[[paste0('log_',y)]]<-log(pmax(p[[y]],1))
run(p,pairs,c('total_jobs','log_total_jobs',sectors,paste0('log_',sectors)),'pooled',paste0('industry/',side))
a<-read_csv(file.path(OUT,'industry',side,'att.csv'),show_col_types=FALSE)%>%filter(outcome=='total_jobs'|outcome%in%sectors)%>%group_by(specification)%>%summarise(error=sum(estimate[outcome%in%sectors])-estimate[outcome=='total_jobs'],.groups='drop')
stopifnot(all(abs(a$error)<1e-7));write_csv(a,file.path(OUT,'industry',side,'additivity.csv'))
